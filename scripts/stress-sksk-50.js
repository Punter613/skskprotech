#!/usr/bin/env node
'use strict';

// Standalone, dependency-free benchmark for the pre-Buyer and current SKSK APIs.
// Intentionally restricted to loopback. Never run synthetic verification on real data.
const fs = require('node:fs');
const { performance } = require('node:perf_hooks');

const SAMPLE_VIN = 'KNDJC736385765089';
const CASES = [
  { symptom: 'Engine runs rough at idle', code: 'P0300', part: 'spark plugs' },
  { symptom: 'Hesitation during acceleration', code: 'P0171', part: 'air filter' },
  { symptom: 'Check engine light illuminated', code: 'P0420', part: 'oxygen sensor' },
  { symptom: 'EVAP warning after refueling', code: 'P0442', part: 'gas cap' },
  { symptom: 'Intermittent cylinder misfire', code: 'P0302', part: 'ignition coil' },
  { symptom: 'Idle speed fluctuates', code: 'P0505', part: 'idle air control' },
  { symptom: 'Brake pedal feels soft', code: 'C0035', part: 'brake pads' }
];

function help() {
  return `SKSK localhost stress test (Node 18+, no npm install)

  node scripts/stress-sksk-50.js --engine legacy --mode fixed --runs 50
  node scripts/stress-sksk-50.js --engine legacy --mode random --runs 50
  node scripts/stress-sksk-50.js --engine legacy --mode concurrent --runs 50 --concurrency 5
  node scripts/stress-sksk-50.js --engine current --mode concurrent --runs 50 --concurrency 5

Options:
  --engine legacy|current     Legacy /api/full-estimate or current /api/diagnose
  --mode fixed|random|concurrent  Same case, random cases, or bounded parallel cases
  --runs N                   Default: 50 (maximum: 500)
  --concurrency N            Concurrent mode only; default: 5 (maximum: 20)
  --url URL                  Loopback base URL only; default: http://127.0.0.1:3000
  --vin VIN                  Test VIN; default: sample 2008 Kia Sorento VIN
  --vins VIN1,VIN2           Optional VIN pool for randomized tests
  --timeout-ms N             Per HTTP step, default: 90000
  --output FILE              JSON report path (auto-generated by default)
  --lifecycle                Current SKSK: also record synthetic test, verify and estimate
  --confirm-isolated-test-server  Required with --lifecycle; server MUST have no real DB
  --help                     Show usage

By default current SKSK benchmarks DIAGNOSE only, because VERIFY must never be
faked in a real shop database. --lifecycle is ONLY for disposable isolated data.`;
}

function parseOptions(argv) {
  const raw = {};
  const flags = new Set(['help', 'lifecycle', 'confirm-isolated-test-server']);
  const allowed = new Set(['engine', 'mode', 'runs', 'concurrency', 'url', 'vin', 'vins', 'timeout-ms', 'output', ...flags]);
  for (let i = 0; i < argv.length; i++) {
    const argument = argv[i];
    if (!argument.startsWith('--')) throw new Error(`Unexpected argument: ${argument}`);
    const equals = argument.indexOf('=');
    const name = argument.slice(2, equals < 0 ? undefined : equals);
    if (!allowed.has(name)) throw new Error(`Unknown option: --${name}`);
    if (Object.hasOwn(raw, name)) throw new Error(`Duplicate option: --${name}`);
    if (flags.has(name)) {
      if (equals >= 0) throw new Error(`--${name} does not take a value`);
      raw[name] = true;
    } else {
      const value = equals >= 0 ? argument.slice(equals + 1) : argv[++i];
      if (!value || value.startsWith('--')) throw new Error(`Missing value for --${name}`);
      raw[name] = value;
    }
  }
  if (raw.help) return { help: true };
  const engine = raw.engine || 'legacy';
  const mode = raw.mode || 'fixed';
  if (!['legacy', 'current'].includes(engine)) throw new Error('Engine must be legacy or current');
  if (!['fixed', 'random', 'concurrent'].includes(mode)) throw new Error('Mode must be fixed, random, or concurrent');
  const boundedInt = (name, fallback, min, max) => {
    const n = raw[name] === undefined ? fallback : Number(raw[name]);
    if (!Number.isSafeInteger(n) || n < min || n > max) throw new Error(`--${name} must be ${min}–${max}`);
    return n;
  };
  const runs = boundedInt('runs', 50, 1, 500);
  const concurrency = mode === 'concurrent' ? boundedInt('concurrency', 5, 1, 20) : 1;
  if (mode !== 'concurrent' && raw.concurrency !== undefined) throw new Error('--concurrency requires --mode concurrent');
  const timeoutMs = boundedInt('timeout-ms', 90000, 100, 300000);
  const target = new URL(raw.url || 'http://127.0.0.1:3000');
  if (target.protocol !== 'http:' || !['127.0.0.1', 'localhost', '[::1]'].includes(target.hostname) ||
      target.username || target.password || target.search || target.hash || target.pathname !== '/') {
    throw new Error('Target must be a plain HTTP loopback origin, e.g. http://127.0.0.1:3000');
  }
  if (raw.lifecycle && engine !== 'current') throw new Error('--lifecycle applies only to --engine current');
  if (raw.lifecycle && !raw['confirm-isolated-test-server']) {
    throw new Error('--lifecycle requires --confirm-isolated-test-server and a disposable server with no real DB');
  }
  const vins = String(raw.vins || raw.vin || SAMPLE_VIN).split(',').map(v => v.trim().toUpperCase());
  if (vins.some(v => !/^[A-HJ-NPR-Z0-9]{17}$/.test(v))) throw new Error('Every VIN must be 17 characters without I/O/Q');
  const output = raw.output || `sksk-stress-${engine}-${new Date().toISOString().replace(/[:.]/g, '-')}.json`;
  return { engine, mode, runs, concurrency, timeoutMs, baseUrl: target.origin, vins, output,
    lifecycle: Boolean(raw.lifecycle) };
}

function percentile(sorted, p) {
  if (!sorted.length) return null;
  return sorted[Math.max(0, Math.ceil(sorted.length * p / 100) - 1)];
}

function statistics(values) {
  const sorted = values.filter(Number.isFinite).sort((a, b) => a - b);
  const round = v => v === null ? null : Math.round(v * 100) / 100;
  if (!sorted.length) return { count: 0, min: null, mean: null, p50: null, p95: null, p99: null, max: null };
  return { count: sorted.length, min: round(sorted[0]),
    mean: round(sorted.reduce((a, b) => a + b, 0) / sorted.length),
    p50: round(percentile(sorted, 50)), p95: round(percentile(sorted, 95)),
    p99: round(percentile(sorted, 99)), max: round(sorted[sorted.length - 1]) };
}

function shortText(value, size = 110) {
  const text = String(value ?? '').replace(/\s+/g, ' ').trim();
  return text.length > size ? `${text.slice(0, size - 1)}…` : text;
}

async function requestJson(config, path, body) {
  const started = performance.now();
  let response;
  try {
    response = await fetch(config.baseUrl + path, {
      method: 'POST', headers: { 'Content-Type': 'application/json', 'X-SKSK-Benchmark': 'synthetic-local-only' },
      body: JSON.stringify(body), signal: AbortSignal.timeout(config.timeoutMs)
    });
  } catch (err) {
    const error = new Error(err.name === 'TimeoutError' ? 'Request timed out' : shortText(err.message));
    error.kind = err.name === 'TimeoutError' ? 'timeout' : 'network';
    error.elapsedMs = performance.now() - started;
    throw error;
  }
  const elapsedMs = performance.now() - started;
  let data;
  try { data = await response.json(); } catch { data = {}; }
  if (!response.ok || data.success === false) {
    const error = new Error(shortText(data.error || data.message || `HTTP ${response.status}`));
    error.kind = response.ok ? 'application' : `http_${response.status}`;
    error.status = response.status;
    error.elapsedMs = elapsedMs;
    throw error;
  }
  return { data, status: response.status, elapsedMs: Math.round(elapsedMs * 100) / 100 };
}

function chooseCase(config, i) {
  const index = config.mode === 'fixed' ? 0 : Math.floor(Math.random() * CASES.length);
  const vin = config.mode === 'fixed' ? config.vins[0] : config.vins[Math.floor(Math.random() * config.vins.length)];
  return { ...CASES[index], vin, run: i };
}

async function legacyEstimate(config, sample) {
  const payload = {
    vin: sample.vin, customerStates: [sample.symptom], mechanicNotices: ['Initial inspection recorded for benchmark only.'],
    obdCodes: [sample.code], mileage: 150000, laborRate: 85, partsCost: 0,
    partType: sample.part, history: []
  };
  const res = await requestJson(config, '/api/full-estimate', payload);
  const data = res.data;
  if (data.success !== true || !data.estimate || !data.meta) {
    const error = new Error('Missing success/estimate/meta response fields');
    error.kind = 'schema'; throw error;
  }
  const diagnosis = shortText(data.estimate.diagnosis);
  const fallback = /simulation|manual inspection required|diagnostic inspection required/i.test(diagnosis) ||
    data.estimate.repairs?.includes('Diagnostic inspection required');
  return { status: res.status, httpMs: res.elapsedMs, serverMs: Number.isFinite(data.duration_ms) ? data.duration_ms : null,
    diagnosis, fallback: Boolean(fallback), reportedAiUsed: data.meta.ai_used === true,
    partsCount: Array.isArray(data.parts) ? data.parts.length : null,
    tsbCount: data.tsb_count ?? null, guideGenerated: Boolean(data.guide) };
}

async function currentEstimate(config, sample) {
  const payload = { vin: sample.vin, vehicle: { year: 2008, make: 'Kia', model: 'Sorento', trim: 'BL 3.8L V6' },
    mileage: 150000, symptoms: [sample.symptom], codes: [sample.code],
    notes: ['Synthetic benchmark input, not a customer record.'] };
  const steps = {};
  const d = await requestJson(config, '/api/diagnose', payload);
  steps.diagnoseMs = d.elapsedMs;
  const jobId = d.data.jobId;
  const cause = shortText(d.data.result?.primaryCause);
  if (!jobId || !cause) {
    const error = new Error('Diagnose did not return jobId and primaryCause');
    error.kind = 'schema'; throw error;
  }
  if (!config.lifecycle) {
    return { status: d.status, steps, diagnosis: cause, lifecycleCompleted: false,
      note: 'DIAGNOSE only; no verification or estimate generated' };
  }
  // Intentionally synthetic. Do not enable this against a persistent shop DB.
  const t = await requestJson(config, `/api/jobs/${encodeURIComponent(jobId)}/tests`, {
    name: `BENCHMARK ONLY — confirmation simulation for ${cause}`,
    result: `SYNTHETIC BENCHMARK: simulated out-of-spec physical measurement for ${cause}; NOT an observed repair fact.`,
    evidenceRole: 'CONFIRMS', confirmedFault: cause, passed: false,
    notes: 'Synthetic only. Delete disposable server/data after run.'
  });
  steps.testMs = t.elapsedMs;
  if (!t.data.test?.id) { const err = new Error('Test response missing persisted test ID'); err.kind = 'schema'; throw err; }
  const v = await requestJson(config, `/api/jobs/${encodeURIComponent(jobId)}/verify`, {
    confirmed: true, confirmedCause: cause, evidenceTestIds: [t.data.test.id],
    conclusion: `SYNTHETIC BENCHMARK ONLY: simulated evidence for ${cause}; no mechanic confirmation occurred.`,
    notes: 'Discard this isolated test job. Not a real vehicle diagnosis.'
  });
  steps.verifyMs = v.elapsedMs;
  if (!v.data.verifiedCase?.fingerprint) {
    const error = new Error('Verify response missing verifiedCase fingerprint'); error.kind = 'schema'; throw error;
  }
  const e = await requestJson(config, '/api/estimateHeuristic', { jobId, laborRate: 85, partsCost: 80 });
  steps.estimateMs = e.elapsedMs;
  const estimate = e.data.estimate || {};
  return { status: e.status, steps, diagnosis: cause,
    estimateDiagnosis: shortText(estimate.diagnosis), estimateTotal: Number(estimate.total ?? 0),
    lifecycleCompleted: true, providerReported: shortText(estimate.aiTrace?.provider),
    fallbackReason: shortText(estimate.aiTrace?.fallbackReason),
    serverEstimateMs: Number.isFinite(estimate.aiTrace?.totalRouteLatencyMs) ? estimate.aiTrace.totalRouteLatencyMs : null };
}

async function runBenchmark(config, onRow = () => {}) {
  const rows = new Array(config.runs);
  let next = 0;
  const started = performance.now();
  async function worker() {
    while (next < config.runs) {
      const index = next++;
      const sample = chooseCase(config, index + 1);
      const began = performance.now();
      let row;
      try {
        const details = config.engine === 'legacy'
          ? await legacyEstimate(config, sample) : await currentEstimate(config, sample);
        row = { run: index + 1, success: true, symptom: sample.symptom, code: sample.code,
          wallMs: Math.round((performance.now() - began) * 100) / 100, ...details };
      } catch (error) {
        row = { run: index + 1, success: false, symptom: sample.symptom, code: sample.code,
          wallMs: Math.round((performance.now() - began) * 100) / 100,
          failure: { kind: error.kind || 'unexpected', status: error.status || null, message: shortText(error.message) } };
      }
      rows[index] = row;
      onRow(row);
    }
  }
  await Promise.all(Array.from({ length: config.concurrency }, worker));
  const elapsedMs = performance.now() - started;
  const good = rows.filter(r => r.success);
  const failures = rows.filter(r => !r.success);
  const failureKinds = {};
  for (const row of failures) failureKinds[row.failure.kind] = (failureKinds[row.failure.kind] || 0) + 1;
  const summary = { total: rows.length, passed: good.length, failed: failures.length,
    fallbackCount: good.filter(r => r.fallback === true).length,
    lifecycleCompleted: good.filter(r => r.lifecycleCompleted === true).length,
    reportedAiUsedCount: good.filter(r => r.reportedAiUsed === true).length,
    elapsedMs: Math.round(elapsedMs * 100) / 100,
    throughputPerSecond: Math.round(rows.length / (elapsedMs / 1000) * 100) / 100,
    wallMs: statistics(rows.map(r => r.wallMs)),
    successfulWallMs: statistics(good.map(r => r.wallMs)),
    serverMs: statistics(good.map(r => r.serverMs).filter(Number.isFinite)),
    failureKinds };
  return { at: new Date().toISOString(), config: { engine: config.engine, mode: config.mode,
    runs: config.runs, concurrency: config.concurrency, baseUrl: config.baseUrl,
    timeoutMs: config.timeoutMs, lifecycle: config.lifecycle }, summary, rows };
}

async function main(argv = process.argv.slice(2)) {
  const config = parseOptions(argv);
  if (config.help) { console.log(help()); return; }
  console.log(`SKSK ${config.engine.toUpperCase()} | ${config.runs} runs | ${config.mode} | concurrency ${config.concurrency}`);
  console.log(`Target: ${config.baseUrl} (loopback only)`);
  if (config.engine === 'current' && !config.lifecycle) console.log('Current mode: DIAGNOSE only (verification and estimate deliberately skipped)');
  if (config.lifecycle) console.log('WARNING: SYNTHETIC VERIFICATION. Use an isolated, disposable server/database ONLY.');
  const result = await runBenchmark(config, row => {
    const label = row.success ? 'OK' : `FAIL ${row.failure.kind}`;
    console.log(`#${String(row.run).padStart(3)} ${label.padEnd(14)} ${String(row.wallMs).padStart(9)} ms | ${shortText(row.diagnosis || row.failure.message, 75)}${row.fallback ? ' [FALLBACK]' : ''}`);
  });
  fs.writeFileSync(config.output, JSON.stringify(result, null, 2) + '\n', { flag: 'wx', mode: 0o600 });
  console.log('\nSUMMARY:', JSON.stringify(result.summary, null, 2));
  console.log(`Report: ${config.output}`);
  if (result.summary.failed) process.exitCode = 1;
}

if (require.main === module) main().catch(err => { console.error(`Stress test: ${err.message}`); process.exitCode = 1; });

module.exports = { parseOptions, percentile, statistics, requestJson, runBenchmark, main };
